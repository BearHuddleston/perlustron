import { pathToFileURL } from "node:url";
import { readFile, writeFile } from "node:fs/promises";

const palettePath = new URL("../src/frontend/palette.json", import.meta.url);
const paletteModulePath = new URL("../src/frontend/palette.ts", import.meta.url);
const stylesPath = new URL("../static/styles.css", import.meta.url);

const START_MARKER = "/* frontend-palette:start */";
const END_MARKER = "/* frontend-palette:end */";
const COLOR_KEY_PATTERN = /^[a-z][a-z0-9-]*$/;
const COLOR_VALUE_PATTERN = /^#[0-9a-f]{6}$/i;
const CSS_PALETTE_VAR_PATTERN = /var\(\s*--map-color-([a-z0-9-]+)\s*\)/g;
const REQUIRED_KIND_COLOR_KEYS = ["prompt", "tool", "compaction"];

export async function readFrontendPalette() {
  return normalizeFrontendPalette(JSON.parse(await readFile(palettePath, "utf8")));
}

export function normalizeFrontendPalette(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error("src/frontend/palette.json must contain an object of color keys to hex values.");
  }

  const entries = Object.entries(value).map(([key, color]) => {
    if (!COLOR_KEY_PATTERN.test(key)) {
      throw new Error(`Invalid frontend palette key: ${key}`);
    }
    if (typeof color !== "string" || !COLOR_VALUE_PATTERN.test(color)) {
      throw new Error(`Invalid frontend palette color for ${key}: ${color}`);
    }

    return [key, color.toLowerCase()];
  });

  return Object.fromEntries(entries);
}

export function paletteCssVariableName(key) {
  return `--map-color-${key}`;
}

export function paletteCssBlock(palette) {
  return [
    START_MARKER,
    ":root {",
    ...Object.entries(palette).map(([key, color]) => `  ${paletteCssVariableName(key)}: ${color};`),
    "}",
    END_MARKER,
  ].join("\n");
}

export function paletteTsModule(palette) {
  const hexEntries = Object.entries(palette).map(([key, color]) => `  ${JSON.stringify(key)}: ${JSON.stringify(color)},`);
  const numberEntries = Object.entries(palette).map(([key, color]) => `  ${JSON.stringify(key)}: 0x${color.slice(1)},`);

  return [
    "// SPDX-License-Identifier: MIT OR Apache-2.0",
    "",
    "// Generated by scripts/sync-frontend-palette.mjs from palette.json.",
    "",
    "export const frontendPalette = {",
    ...hexEntries,
    "} as const;",
    "",
    "export type PaletteKey = keyof typeof frontendPalette;",
    "",
    "export const kindColor: Record<string, number> = {",
    ...numberEntries,
    "};",
    "",
  ].join("\n");
}

export function mapColorVariableKeys(styles) {
  return [...new Set([...styles.matchAll(CSS_PALETTE_VAR_PATTERN)].map((match) => match[1]))].sort();
}

export function assertFrontendPaletteCoversUsage(palette, styles) {
  const requiredKeys = [...new Set([...REQUIRED_KIND_COLOR_KEYS, ...mapColorVariableKeys(styles)])].sort();
  const missingKeys = requiredKeys.filter((key) => !palette[key]);

  if (missingKeys.length) {
    throw new Error(`src/frontend/palette.json is missing colors for: ${missingKeys.join(", ")}`);
  }
}

export function syncPaletteCssBlock(styles, palette) {
  const start = styles.indexOf(START_MARKER);
  const end = styles.indexOf(END_MARKER);

  if (start < 0 || end < 0 || end < start) {
    throw new Error(`static/styles.css must contain ${START_MARKER} and ${END_MARKER}.`);
  }

  const blockEnd = end + END_MARKER.length;
  return `${styles.slice(0, start)}${paletteCssBlock(palette)}${styles.slice(blockEnd)}`;
}

export async function syncFrontendPaletteAssets({ check = false, styles = null, paletteModule = null } = {}) {
  const palette = await readFrontendPalette();
  const [currentStyles, currentPaletteModule] = await Promise.all([
    styles ?? readFile(stylesPath, "utf8"),
    paletteModule ?? readFile(paletteModulePath, "utf8"),
  ]);
  assertFrontendPaletteCoversUsage(palette, currentStyles);
  const updatedStyles = syncPaletteCssBlock(currentStyles, palette);
  const updatedPaletteModule = paletteTsModule(palette);
  const staleOutputs = [];

  if (updatedStyles !== currentStyles) {
    staleOutputs.push("static/styles.css palette variables");
  }
  if (updatedPaletteModule !== currentPaletteModule) {
    staleOutputs.push("src/frontend/palette.ts");
  }

  if (check && staleOutputs.length) {
    throw new Error(`${staleOutputs.join(" and ")} are stale. Run npm run build:frontend.`);
  }

  if (!check) {
    await Promise.all([
      updatedStyles !== currentStyles ? writeFile(stylesPath, updatedStyles) : null,
      updatedPaletteModule !== currentPaletteModule ? writeFile(paletteModulePath, updatedPaletteModule) : null,
    ]);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await syncFrontendPaletteAssets();
}
